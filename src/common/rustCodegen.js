(function (root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory(require("./rustContract"));
  } else {
    root.RustyCodegen = factory(root.RustyContract);
  }
})(typeof globalThis !== "undefined" ? globalThis : this, function (contract) {
  "use strict";

  const { toSnakeCase, toPascalCase, toCrateName, defaultStateCode } = contract;

  function formatRustDefaultValue(rustType, rawVal) {
    const t = String(rustType || "i32").trim();
    const v = rawVal !== undefined && rawVal !== null ? String(rawVal).trim() : "";
    if (t === "bool") {
      return v === "true" ? "true" : "false";
    }
    if (t === "String") {
      const stripped = v.replace(/^"(.*)"$/, "$1");
      return `String::from(${JSON.stringify(stripped)})`;
    }
    if (t === "f64" || t === "f32") {
      if (!v) return "0.0";
      return v.includes(".") ? v : `${v}.0`;
    }
    // integer types (i32, i64, u32, u64, usize)
    return v && /^-?\d+$/.test(v) ? v : "0";
  }

  function generateCargoToml(model) {
    const crateName = toCrateName(model.crateName || model.name || "rusty_machine");
    const desc = String(model.description || "Generated by Rusty Studio (WebGME + webgme-git)").replace(/"/g, '\\"');
    return `[package]
name = "${crateName}"
version = "0.1.0"
edition = "2021"
description = "${desc}"

[lib]
name = "${toSnakeCase(crateName)}"
path = "src/lib.rs"

[[bin]]
name = "${crateName}"
path = "src/main.rs"
`;
  }

  function generateTypesRs(model) {
    const states = model.states || [];
    const globals = model.globals || [];
    const events = model.events || [];

    const stateVariants =
      states.length > 0
        ? states.map((s) => `    ${toPascalCase(s.name)},`).join("\n")
        : "    Idle,";

    const stateNameArms =
      states.length > 0
        ? states.map((s) => `            StateId::${toPascalCase(s.name)} => "${s.name}",`).join("\n")
        : '            StateId::Idle => "Idle",';

    const eventVariants =
      events.length > 0
        ? events
            .map((e) => {
              const evName = toPascalCase(e.name);
              const payload = (e.payloadType || "").trim();
              return payload ? `    ${evName}(${payload}),` : `    ${evName},`;
            })
            .join("\n")
        : "    Tick,";

    const eventParseArms =
      events.length > 0
        ? events
            .map((e) => {
              const evName = toPascalCase(e.name);
              const payload = (e.payloadType || "").trim();
              if (!payload) {
                return e.name === evName
                  ? `            "${evName}" => Some(Event::${evName}),`
                  : `            "${e.name}" | "${evName}" => Some(Event::${evName}),`;
              }
              if (payload === "String") {
                return `            s if s.starts_with("${e.name}:") => Some(Event::${evName}(s["${e.name}:".len()..].to_string())),`;
              }
              return `            s if s.starts_with("${e.name}:") => s["${e.name}:".len()..].parse::<${payload}>().ok().map(Event::${evName}),`;
            })
            .join("\n")
        : '            "Tick" => Some(Event::Tick),';

    const globalFields =
      globals.length > 0
        ? globals
            .map((g) => `    pub ${toSnakeCase(g.name)}: ${g.rustType || "i32"},`)
            .join("\n")
        : "    pub _reserved: u32,";

    const globalDefaults =
      globals.length > 0
        ? globals
            .map(
              (g) =>
                `            ${toSnakeCase(g.name)}: ${formatRustDefaultValue(g.rustType, g.initialValue)},`,
            )
            .join("\n")
        : "            _reserved: 0,";

    const globalJsonParts =
      globals.length > 0
        ? globals
            .map((g) => {
              const field = toSnakeCase(g.name);
              if (g.rustType === "String") {
                return `            format!("\\"${field}\\":\\"{}\\"", self.${field}.replace('"', "\\\\\\""))`;
              }
              return `            format!("\\"${field}\\":{}", self.${field})`;
            })
            .join(",\n")
        : '            format!("\\"_reserved\\":{}", self._reserved)';

    return `//! Generated shared types from WebGME StateMachine: ${model.name || "StateMachine"}
//! Do not hand-edit — regenerate from Rusty Studio.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StateId {
${stateVariants}
}

impl StateId {
    pub fn as_str(&self) -> &'static str {
        match self {
${stateNameArms}
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub enum Event {
${eventVariants}
}

impl Event {
    pub fn parse(raw: &str) -> Option<Self> {
        match raw.trim() {
${eventParseArms}
            _ => None,
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub enum Outcome {
    Stay,
    Transition(StateId),
    Emit(Event),
}

#[derive(Debug, Clone, PartialEq)]
pub struct Globals {
${globalFields}
}

impl Default for Globals {
    fn default() -> Self {
        Self {
${globalDefaults}
        }
    }
}

impl Globals {
    pub fn to_json(&self) -> String {
        let parts = [
${globalJsonParts}
        ];
        format!("{{{}}}", parts.join(","))
    }
}
`;
  }

  function generateStatesModRs(model) {
    const states = model.states || [];
    return (
      "//! State modules synchronized via webgme-git.\n\n" +
      states.map((s) => `pub mod ${toSnakeCase(s.name)};`).join("\n") +
      "\n"
    );
  }

  function generateMachineRs(model) {
    const states = model.states || [];
    const transitions = model.transitions || [];
    const initialState = states.find((s) => s.isInitial) || states[0];
    const initialVariant = initialState ? toPascalCase(initialState.name) : "Idle";

    const enterArms = states
      .map(
        (s) =>
          `            StateId::${toPascalCase(s.name)} => states::${toSnakeCase(s.name)}::on_enter(&mut self.globals),`,
      )
      .join("\n");

    const exitArms = states
      .map(
        (s) =>
          `            StateId::${toPascalCase(s.name)} => states::${toSnakeCase(s.name)}::on_exit(&mut self.globals),`,
      )
      .join("\n");

    const eventArms = states
      .map(
        (s) =>
          `            StateId::${toPascalCase(s.name)} => states::${toSnakeCase(s.name)}::on_event(&mut self.globals, &current_ev),`,
      )
      .join("\n");

    // Fallback model-level transition table for states whose code returns Outcome::Stay
    const sortedTransitions = [...transitions].sort(
      (a, b) => (Number(a.priority) || 0) - (Number(b.priority) || 0),
    );
    const modelTransitionChecks = sortedTransitions
      .filter((t) => t.srcName && t.dstName && t.event)
      .map((t) => {
        const src = toPascalCase(t.srcName);
        const dst = toPascalCase(t.dstName);
        const ev = toPascalCase(t.event);
        const evDef = (model.events || []).find((e) => toPascalCase(e.name) === ev);
        const evPattern = evDef && evDef.payloadType ? `Event::${ev}(_)` : `Event::${ev}`;
        const guard = t.guard && t.guard.trim() ? ` && (${t.guard.trim()})` : "";
        return `        if self.current == StateId::${src} && matches!(event, ${evPattern})${guard} {\n            return Some(StateId::${dst});\n        }`;
      })
      .join("\n");

    return `//! Generated state machine dispatcher for ${model.name || "StateMachine"}.

use crate::states;
use crate::types::{Event, Globals, Outcome, StateId};

pub struct StateMachine {
    pub current: StateId,
    pub globals: Globals,
    pub step_count: u64,
}

impl StateMachine {
    pub fn new() -> Self {
        let mut sm = Self {
            current: StateId::${initialVariant},
            globals: Globals::default(),
            step_count: 0,
        };
        sm.enter_current();
        sm
    }

    fn enter_current(&mut self) {
        match self.current {
${enterArms}
        }
    }

    fn exit_current(&mut self) {
        match self.current {
${exitArms}
        }
    }

    fn evaluate_model_transitions(&self, event: &Event) -> Option<StateId> {
        let globals = &self.globals;
        let _ = (globals, event);
${modelTransitionChecks || "        None"}
${modelTransitionChecks ? "        None" : ""}
    }

    pub fn dispatch(&mut self, event: &Event) -> (StateId, StateId) {
        let initial_from = self.current;
        let mut pending: Option<Event> = Some(event.clone());
        let mut depth = 0u8;

        while let Some(current_ev) = pending.take() {
            if depth >= 8 {
                break;
            }
            depth += 1;

            let outcome = match self.current {
${eventArms}
            };

            let next_state = match outcome {
                Outcome::Transition(target) => Some(target),
                Outcome::Emit(emitted) => {
                    pending = Some(emitted);
                    None
                }
                Outcome::Stay => self.evaluate_model_transitions(&current_ev),
            };

            if let Some(target) = next_state {
                if target != self.current {
                    self.exit_current();
                    self.current = target;
                    self.enter_current();
                }
            }
        }

        self.step_count += 1;
        (initial_from, self.current)
    }
}

impl Default for StateMachine {
    fn default() -> Self {
        Self::new()
    }
}
`;
  }

  function generateLibRs(model) {
    return `//! Crate root for ${model.name || "StateMachine"}
//! Generated by Rusty Studio (WebGME topology + webgme-git Rust state files).

pub mod types;
pub mod states;
pub mod machine;

pub use machine::StateMachine;
pub use types::{Event, Globals, Outcome, StateId};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn initializes_in_valid_state() {
        let sm = StateMachine::new();
        assert!(!sm.current.as_str().is_empty());
    }
}
`;
  }

  function generateMainRs(model) {
    const crateIdent = toSnakeCase(toCrateName(model.crateName || model.name || "rusty_machine"));
    return `//! CLI trace runner for ${model.name || "StateMachine"}.
//! Usage: cargo run -- Start Tick Tick Stop

use ${crateIdent}::{Event, StateMachine};

fn main() {
    let mut sm = StateMachine::new();
    let args: Vec<String> = std::env::args().skip(1).collect();

    println!(
        "{{\\"step\\":0,\\"event\\":\\"__init__\\",\\"from\\":\\"{}\\",\\"to\\":\\"{}\\",\\"globals\\":{}}}",
        sm.current.as_str(),
        sm.current.as_str(),
        sm.globals.to_json()
    );

    for raw in args {
        match Event::parse(&raw) {
            Some(ev) => {
                let (from, to) = sm.dispatch(&ev);
                println!(
                    "{{\\"step\\":{},\\"event\\":\\"{}\\",\\"from\\":\\"{}\\",\\"to\\":\\"{}\\",\\"globals\\":{}}}",
                    sm.step_count,
                    raw.replace('"', "\\\\\\""),
                    from.as_str(),
                    to.as_str(),
                    sm.globals.to_json()
                );
            }
            None => {
                eprintln!("Unknown event: {}", raw);
            }
        }
    }
}
`;
  }

  function generateCrateFiles(model) {
    const files = {};
    files["Cargo.toml"] = generateCargoToml(model);
    files["src/types.rs"] = generateTypesRs(model);
    files["src/states/mod.rs"] = generateStatesModRs(model);
    files["src/machine.rs"] = generateMachineRs(model);
    files["src/lib.rs"] = generateLibRs(model);
    files["src/main.rs"] = generateMainRs(model);

    const transitions = model.transitions || [];
    for (const st of model.states || []) {
      const modName = toSnakeCase(st.name);
      const outgoing = transitions.filter((t) => t.srcName === st.name);
      const code =
        st.code && st.code.trim()
          ? st.code
          : defaultStateCode(st.name, outgoing);
      files[`src/states/${modName}.rs`] = code;
    }

    return files;
  }

  return {
    generateCrateFiles,
    generateCargoToml,
    generateTypesRs,
    generateMachineRs,
  };
});
